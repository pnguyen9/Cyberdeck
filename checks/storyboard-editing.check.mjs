// Editing pages from the keyboard: the board focused on arrival, Alt+G between the board and the page
// edited, nothing unsaved lost without asking (another card, Esc, another tab), and the side panel
// sliding over the board in a narrow window.
import { createProjectWithSample, pause } from './harness.mjs'

export default async function check(page, { url }) {
  const active = () => page.evaluate(`document.activeElement?.classList.contains('board') ? 'board' : document.activeElement?.classList.contains('field') ? 'editor' : document.activeElement?.tagName`)
  const focusedText = () => page.evaluate(`document.querySelector('.grid .element.focused .text')?.textContent.trim()`)
  const question = () => page.evaluate(`document.querySelector('.pending p')?.textContent ?? null`)
  const fieldValue = () => page.evaluate(`document.querySelector('.tag-editor .field')?.value ?? null`)

  await createProjectWithSample(page, url, 'Editing')
  await page.clickButton('Storyboard', '.tab')
  await page.waitFor('.grid')
  await pause(300)
  page.check('the board has the focus on arrival', await active(), 'board')

  await page.evaluate(`document.querySelector('.chapter-picker select').focus()`)
  await page.press('g', { alt: true })
  await pause(200)
  page.check('Alt+G comes back to the board and selects the first card', [await active(), await page.evaluate(`document.querySelectorAll('.grid .element.selected').length`)], ['board', 1])

  await page.press('ArrowRight')
  await page.press('ArrowRight')
  await page.press('Enter')
  await pause(300)
  page.check('Enter opens the page in the panel', await active(), 'editor')
  await page.press('End', { ctrl: true })
  await page.typeText(' Smiling.')
  await pause(200)
  await page.press('g', { alt: true })
  await pause(200)
  page.check('Alt+G from the page goes to its card, the edit kept open', [await active(), await focusedText(), (await fieldValue())?.endsWith('Smiling.')], ['board', 'You came after all.', true])
  page.check('the card edited is marked', await page.evaluate(`document.querySelector('.grid .element.editing .text')?.textContent.trim()`), 'You came after all.')
  await page.press('g', { alt: true })
  await pause(200)
  page.check('and Alt+G again goes back into the page', await active(), 'editor')

  await page.press('g', { alt: true })
  await page.press('ArrowRight')
  await page.press('Enter')
  await pause(300)
  page.check('opening another card asks first', await question(), 'Your changes to the page open are not saved.')
  page.check('the changes are still there meanwhile', (await fieldValue())?.endsWith('Smiling.'), true)
  await page.screenshot('asking')
  await page.clickButton('Keep editing', '.pending .button')
  await pause(200)
  page.check('keeping on editing goes back into the page', [await question(), await active()], [null, 'editor'])

  await page.press('g', { alt: true })
  await pause(200)
  await page.press('Delete')
  await pause(300)
  page.check('removing cards meanwhile asks too, the card still there', [await question(), await page.evaluate(`[...document.querySelectorAll('.grid .text')].some(text => text.textContent === 'You came after all.')`)], ['Your changes to the page open are not saved: save them, or drop them, before removing cards.', true])
  await page.clickButton('Keep editing', '.pending .button')
  await pause(200)

  await page.press('Escape')
  await pause(200)
  page.check('Esc with changes asks too', await question(), 'Close without saving your changes?')
  await page.clickButton('Discard', '.pending .button')
  await pause(200)
  page.check('discarding closes the edit, on its card', [await fieldValue(), await active(), await focusedText()], [null, 'board', 'You came after all.'])

  await page.press('Enter')
  await pause(300)
  await page.press('End', { ctrl: true })
  await page.typeText(' Again.')
  await pause(200)
  await page.press('PageDown', { alt: true })
  await pause(200)
  page.check('another tab waits for an answer too', [await question(), await page.evaluate(`document.querySelector('.tab.current').textContent.trim()`)], ['Your changes to the page open are not saved.', 'Storyboard'])
  await page.clickButton('Save', '.pending .button')
  await pause(600)
  page.check('saving then goes to that tab', await page.evaluate(`document.querySelector('.tab.current').textContent.trim()`), 'Import')
  await page.press('PageUp', { alt: true })
  await page.waitFor('.grid')
  await pause(300)
  page.check('the change was saved', await page.evaluate(`[...document.querySelectorAll('.grid .text')].some(text => text.textContent.includes('Again.'))`), true)

  await page.send('Emulation.setDeviceMetricsOverride', { width: 800, height: 700, deviceScaleFactor: 1, mobile: false })
  await pause(400)
  const panelShown = () => page.evaluate(`getComputedStyle(document.querySelector('.inspector')).visibility === 'visible' && document.querySelector('.inspector').getBoundingClientRect().right <= window.innerWidth + 1`)
  page.check('in a narrow window, the panel waits at the edge', [await panelShown(), await page.evaluate(`getComputedStyle(document.querySelector('.panel-handle')).display !== 'none'`)], [false, true])
  await page.evaluate(`document.querySelectorAll('.grid .lane > .elements > .element.card')[3].click()`)
  await pause(400)
  page.check('a card clicked slides it in, over the board, at the top of the window', [await panelShown(), await page.evaluate(`document.querySelector('.inspector').getBoundingClientRect().top`)], [true, 0])
  await page.screenshot('narrow-panel')
  await page.press('p', { alt: true })
  await pause(400)
  page.check('Alt+P slides it away', await panelShown(), false)
  page.check('no horizontal scroll', await page.evaluate(`document.documentElement.scrollWidth <= window.innerWidth`), true)
}
