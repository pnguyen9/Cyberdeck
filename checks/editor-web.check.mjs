// The editor end to end: projects, import, problems, cast and files, details, chapters, preview,
// reload, partial export, backup and restore, as a copy too; then the partial export installed in Datajack.
import { readdirSync } from 'node:fs'
import { createProfile, createProject, installGame, pause, shownStep } from './harness.mjs'

export default async function check(page, { url, assets, serve }) {
  const chapterTitles = () => page.evaluate(`[...document.querySelectorAll('.chapter .title')].map(title => title.textContent).join(' | ')`)
  /** Clicks an action of the chapter at that position in the list. */
  const chapterAction = (index, label) => page.evaluate(`[...[...document.querySelectorAll('.chapter')][${index}].querySelectorAll('.actions .link-button')].find(button => button.textContent.trim() === ${JSON.stringify(label)}).click()`)

  await page.navigate(url)
  await page.waitFor('.new-project')
  page.check('Cyberdeck starts on the projects', (await page.evaluate(`document.querySelector('.muted')?.textContent`))?.startsWith('No project yet'), true)
  await createProject(page, url, 'The Letter')
  await page.watchViolations()
  page.check('a new project opens on the import', await page.evaluate(`document.querySelector('.tab.current')?.textContent.trim()`), 'Import')

  await page.clickButton('Use the sample story')
  await pause(500)
  page.check('the import summarises the text', (await page.evaluate(`[...document.querySelectorAll('.import p.muted')].map(paragraph => paragraph.textContent).join()`))?.includes('1 chapter (Chapter 1 — The Letter)'), true)
  await page.clickButton('Import', '.import-actions .button')
  await pause(800)
  page.check('importing reports the chapters', await page.statusText(), 'Imported 1 chapter: Chapter 1 — The Letter.')
  page.check('and lists them', await chapterTitles(), 'Chapter 1 — The Letter')
  page.check('a chapter tells where it came from', (await page.evaluate(`document.querySelector('.chapter .details')?.textContent`))?.includes('Imported on'), true)

  await page.clickButton('Import', '.tab')
  await pause(300)
  await page.setValue('.source', ['# Chapter 2 — The Rooftop', '[bg: rooftop]', '[enter: marie]', '— Marie: Here again.', '[if: Answer is Truth]', 'She smiled.', '[end]'].join('\n'))
  await pause(400)
  page.check('a second chapter knows the names of the first', await page.evaluate(`document.querySelectorAll('.problems li').length`), 0)
  await page.clickButton('Import', '.import-actions .button')
  await pause(800)
  page.check('two chapters now', await chapterTitles(), 'Chapter 1 — The Letter | Chapter 2 — The Rooftop')

  await page.clickButton('Import', '.tab')
  await pause(300)
  await page.setValue('.source', '[if: Mood is Happy]\nHello.\n[end]')
  await pause(400)
  page.check('errors are listed', (await page.evaluate(`document.querySelector('.problems li.error')?.textContent`))?.startsWith('Line 1'), true)
  page.check('importing waits for them to be fixed', await page.evaluate(`[...document.querySelectorAll('.import-actions .button')].find(button => button.textContent.trim() === 'Import').disabled`), true)
  await page.setValue('.source', '')

  await page.clickButton('Cast & files', '.tab')
  await page.waitFor('.drop-zone .file-input')
  await page.setFiles('.drop-zone .file-input', readdirSync(assets).map(fileName => `${assets}/${fileName}`))
  await pause(1200)
  const castReport = await page.statusText()
  page.check('files go to the entries named like them', castReport?.includes('Marie-Smile.svg → Marie, smile') && castReport?.includes('Rooftop.svg → Background rooftop'), true)
  // The sample story names no sound: the test knock is one more file of no entry.
  page.check('files of no entry are reported', castReport?.includes('Not used, no entry of that name: door.wav, street.svg.'), true)
  page.check('thumbnails show the files', await page.evaluate(`[...document.querySelectorAll('img.thumbnail')].filter(image => image.complete && image.naturalWidth > 0).length >= 5`), true)
  await page.setValue('.drawn-facing select', 'right', 'change')
  await pause(400)
  await page.screenshot('editor-cast')

  await page.clickButton('Details', '.tab')
  await page.waitFor('.details textarea')
  await page.setValue('.details textarea', 'An empty classroom, a letter, and a choice.', 'input')
  await page.setValue('.details textarea', 'An empty classroom, a letter, and a choice.', 'change')
  await pause(400)
  await page.setFiles('.cover-actions input[type=file]', [`${assets}/Rooftop.svg`])
  await pause(800)
  page.check('the cover is shown', await page.evaluate(`(() => { const image = document.querySelector('.cover img'); return image !== null && image.complete && image.naturalWidth > 0 })()`), true)

  await page.clickButton('Chapters', '.tab')
  await pause(300)
  await chapterAction(1, 'Move up')
  await pause(500)
  page.check('a chapter moves up', await chapterTitles(), 'Chapter 2 — The Rooftop | Chapter 1 — The Letter')
  await chapterAction(0, 'Move down')
  await pause(500)
  await chapterAction(1, 'Preview from here ▶')
  await page.waitFor('.viewport .text')
  await pause(500)
  page.check('previewing from a chapter plays it', await shownStep(page), 'Here again.')
  page.check('with the background given', await page.evaluate(`[...document.querySelectorAll('.viewport .background')].some(element => getComputedStyle(element).backgroundImage.includes('blob:'))`), true)
  await page.screenshot('editor-preview')
  await page.evaluate(`document.querySelector('.leave-button').click()`)
  await pause(500)
  page.check('leaving the preview comes back to the same tab', await page.evaluate(`document.querySelector('.tab.current')?.textContent.trim()`), 'Chapters')
  page.check('no content security violation', await page.violations(), '[]')

  await page.reload()
  await page.waitFor('.open-project')
  page.check('the project is listed after a reload', await page.evaluate(`document.querySelector('.project-name')?.textContent`), 'The Letter')
  await page.evaluate(`document.querySelector('.open-project').click()`)
  await page.waitFor('.chapter')
  page.check('its chapters are kept', await chapterTitles(), 'Chapter 1 — The Letter | Chapter 2 — The Rooftop')
  await page.clickButton('Cast & files', '.tab')
  await pause(500)
  page.check('its files are kept', await page.evaluate(`document.querySelectorAll('.present').length >= 6`), true)
  page.check('and the way a sprite is drawn', await page.evaluate(`document.querySelector('.drawn-facing select').value`), 'right')

  await page.clickButton('Export', '.tab')
  await pause(300)
  await page.evaluate(`document.querySelector('.export .chapters input[type=checkbox]').click()`)
  await pause(200)
  await page.clickButton('Export', '.export .button')
  await page.waitFor('.export .download')
  page.check('exporting some chapters names them', await page.evaluate(`document.querySelector('.export .download')?.getAttribute('download')`), 'The Letter 1.0 - Chapter 2 — The Rooftop.zip')
  const archive = await page.saveDownload('update.zip', '.export .download')

  await page.clickButton('Back up')
  await page.waitFor('.backup .download')
  page.check('a backup is offered', await page.evaluate(`document.querySelector('.backup .download')?.getAttribute('download')`), 'The Letter backup.zip')
  const backup = await page.saveDownload('backup.zip', '.backup .download')
  await page.clickButton('← Projects')
  await pause(800)
  await page.clickButton('Delete', '.link-button')
  await pause(200)
  await page.clickButton('Delete', '.button')
  await pause(800)
  page.check('deleting empties the list', (await page.evaluate(`document.querySelector('.muted')?.textContent`))?.startsWith('No project yet'), true)
  await page.setFiles('.file-button input[type=file]', [backup])
  await pause(1500)
  page.check('restoring a backup reports it', await page.statusText(), 'The Letter was restored.')
  await page.evaluate(`document.querySelector('.open-project').click()`)
  await page.waitFor('.chapter')
  page.check('the restored project has its chapters', await chapterTitles(), 'Chapter 1 — The Letter | Chapter 2 — The Rooftop')
  await page.clickButton('← Projects')
  await pause(800)
  await page.setFiles('.file-button + .file-button input[type=file]', [backup])
  await pause(1500)
  page.check('restored as a copy, the backup comes beside its project', [await page.statusText(), await page.evaluate(`[...document.querySelectorAll('.project-name')].map(name => name.textContent.trim()).sort()`)], [
    'The Letter (copy) was added.',
    ['The Letter', 'The Letter (copy)'],
  ])
  await page.evaluate(`document.querySelector('.open-project').click()`)
  await page.waitFor('.chapter')

  await createProfile(page, await serve('datajack'), 'Pascal')
  await installGame(page, archive)
  page.check('Datajack installs the update', await page.statusText(), 'The Letter 1.0 installed.')
  page.check('and names the chapter it lacks', await page.evaluate(`document.querySelector('.chapters')?.textContent.trim()`), '1 of 2 chapters · not installed: Chapter 1 — The Letter')
  await page.screenshot('datajack-partial')
}
