// The log, save slots, saves as files and the autosave of the player: a game exported from Cyberdeck,
// played in Datajack.
import { writeFileSync } from 'node:fs'
import { advanceUntil, createProfile, createProjectWithSample, exportGame, installGame, pause, shownStep } from './harness.mjs'

export default async function check(page, { url, serve, output }) {
  await createProjectWithSample(page, url, 'The Letter')
  const archive = await exportGame(page, 'The Letter.zip')
  await createProfile(page, await serve('datajack'), 'Pascal')
  await installGame(page, archive)
  await page.clickButton('Play', '.button')
  await page.waitFor('.viewport .text')

  await advanceUntil(page, step => step === 'CHOICE')
  await pause(500)
  await page.evaluate(`document.querySelectorAll('.viewport .option')[0].click()`)
  await pause(300)
  await advanceUntil(page, step => step.startsWith('I would never laugh'))
  page.check('the page after the choice is reached', (await shownStep(page)).startsWith('I would never laugh'), true)

  await page.press('l')
  await pause(150)
  const logLines = await page.evaluate(`[...document.querySelectorAll('.line')].map(line => line.textContent.trim())`)
  page.check('L opens the log, with the option picked', logLines.some(line => line.includes('▸ Tell her the truth.')), true)
  await page.screenshot('log')
  await page.evaluate(`document.querySelectorAll('.line')[2].click()`)
  await pause(300)
  page.check('clicking a line of the log goes back to it', await shownStep(page), 'You came after all.')

  await page.clickButton('Save', '.quick-button')
  await pause(300)
  await page.evaluate(`document.querySelectorAll('.slot')[0].click()`)
  await pause(300)
  page.check('saving shows a notice', await page.evaluate(`document.querySelector('.notice')?.textContent`), 'Saved in slot 1.')
  await advanceUntil(page, step => step === 'CHOICE')
  await page.clickButton('Load', '.quick-button')
  await pause(300)
  await page.screenshot('load')
  await page.evaluate(`[...document.querySelectorAll('.slot')].find(slot => slot.textContent.includes('Slot 1')).click()`)
  await pause(400)
  page.check('loading slot 1 returns to the saved page', await shownStep(page), 'You came after all.')

  await page.press(' ')
  await page.press(' ')
  await pause(200)
  const pageBeforeLeaving = await shownStep(page)
  await page.press('Escape')
  await pause(500)
  page.check('Esc leaves for the library, which offers Continue', await page.clickButton('Continue', '.button'), true)
  await page.waitFor('.viewport .text')
  await pause(300)
  page.check('Continue resumes the last page', await shownStep(page), pageBeforeLeaving)

  await page.press('Escape')
  await page.reload()
  await page.waitFor('.game')
  page.check('after a reload, Continue is still offered', await page.evaluate(`[...document.querySelectorAll('.button')].some(button => button.textContent.trim() === 'Continue')`), true)

  await page.clickButton('Continue', '.button')
  await page.waitFor('.viewport .text')
  await pause(300)
  const savedPage = await shownStep(page)
  await page.clickButton('Save', '.quick-button')
  await pause(300)
  page.check('the save is offered as a file, named after the game and the time', /^The Letter \d{4}-\d\d-\d\d \d\dh\d\d\.json$/.test(await page.evaluate(`document.querySelector('.file-link')?.getAttribute('download')`)), true)
  const saveFile = await page.saveDownload('saved.json', '.file-link')
  await page.screenshot('save-to-file')
  await page.press('Escape')
  await advanceUntil(page, step => step === 'CHOICE')
  await page.press('Escape')
  await pause(500)
  await page.setFiles('.load-button .file-input', [saveFile])
  await page.waitFor('.viewport .text')
  await pause(400)
  page.check('a save file opens the game where it was saved', await shownStep(page), savedPage)
  await page.press('Escape')
  await pause(500)
  writeFileSync(`${output}/not-a-save.json`, '{"game": 3}')
  await page.setFiles('.load-button .file-input', [`${output}/not-a-save.json`])
  await pause(400)
  page.check('anything else is refused', await page.evaluate(`document.querySelector('.error')?.textContent`), 'not-a-save.json is not a save.')
}
